/** 查内置地名表:名字带"市/县/区/镇"后缀也能匹配上 */
export function lookupPlace(
  name: string,
): { latitude: number; longitude: number } | null {
  const key = name.trim();
  const bare = key.replace(/(省|市|县|区|镇|乡|自治州|地区|盟)$/u, "");
  const hit = KNOWN_PLACES[key] ?? KNOWN_PLACES[bare];
  return hit ? { latitude: hit[0], longitude: hit[1] } : null;
}
